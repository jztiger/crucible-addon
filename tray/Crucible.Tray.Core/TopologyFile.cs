using System;
using System.Globalization;
using System.Text;

namespace Crucible.Tray
{
    /// <summary>The topology file the addon reads (spec §4.1). Text only; the caller writes it with AtomicFile.</summary>
    public static class TopologyFile
    {
        public const string Name = "Topology.lua";
        private static readonly UTF8Encoding NoBom = new UTF8Encoding(false);

        public static string Render(PlanResult plan, string companionVersion, DateTime nowUtc)
        {
            if (!plan.Ok) throw new InvalidOperationException("no topology for a refused plan: " + plan.Reason);
            var sb = new StringBuilder();
            sb.Append("-- Generated by Crucible. Rewritten whenever the WoW window is spanned. Do not edit.\n");
            sb.Append("CrucibleCanvasTopology = {\n");
            sb.Append("  schema = 1,\n");
            sb.Append("  generatedAt = ").Append(Q(nowUtc.ToUniversalTime().ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture))).Append(",\n");
            sb.Append("  companionVersion = ").Append(Q(companionVersion)).Append(",\n");
            sb.Append("  mode = ").Append(Q(plan.Mode)).Append(",\n");
            sb.Append("  window = { width = ").Append(plan.Window.Width).Append(", height = ").Append(plan.Window.Height).Append(" },\n");
            sb.Append("  mainhand = ").Append(R(plan.Mainhand)).Append(",\n");
            sb.Append("  workspace = ").Append(R(plan.Workspace)).Append(",\n");
            sb.Append("  devices = { mainhand = ").Append(Q(plan.MainhandId)).Append(", workspace = ").Append(Q(plan.WorkspaceId)).Append(" },\n");
            sb.Append("}\n");
            return sb.ToString();
        }

        public static byte[] Bytes(string text) => NoBom.GetBytes(text);

        private static string R(Rect r) => "{ x = " + r.Left + ", y = " + r.Top + ", width = " + r.Width + ", height = " + r.Height + " }";
        private static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\"";
    }
}
