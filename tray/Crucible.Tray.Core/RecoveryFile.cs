using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

namespace Crucible.Tray
{
    public sealed class Extracted
    {
        public int Revision { get; set; }
        public string Base64 { get; set; } = "";
    }

    /// <summary>Spec §4.2. The saved file is never parsed or executed: regular expressions lift the chunk strings and the
    /// sentinel out, as src/shared/sv-extract.ts does for the AH addon. Anything that does not add up is refused whole.</summary>
    public static class RecoveryFile
    {
        public const string Name = "Recovery.lua";
        public const long MaxSavedBytes = 8L * 1024 * 1024;
        public const int MaxBase64Chars = 1024 * 1024;
        private static readonly Regex Chunk = new Regex("\"cc1:([0-9]{1,9}):([0-9]{1,5})/([0-9]{1,5}):([^\"]*)\"", RegexOptions.CultureInvariant);
        private static readonly Regex AnySentinel = new Regex("\"cc1end:[^\"]*\"", RegexOptions.CultureInvariant);
        private static readonly Regex Sentinel = new Regex("^\"cc1end:([0-9]{1,9}):([0-9]{1,5})\"\\z", RegexOptions.CultureInvariant);
        private static readonly Regex Base64Shape = new Regex("^[A-Za-z0-9+/]+={0,2}\\z", RegexOptions.CultureInvariant);
        private static readonly UTF8Encoding NoBom = new UTF8Encoding(false);

        public static Extracted? Extract(string savedText, out string reason)
        {
            reason = "";
            if (savedText.IndexOf('\0') >= 0) { reason = "nul bytes"; return null; }
            // Exactly one well-formed sentinel (ruling R8b): every "cc1end:" string is checked, two complete sets or a
            // malformed sentinel refuse the whole file - the addon's State.fromChunks applies the same rule.
            // Digits are [0-9], not \d (which admits any Unicode digit and would make int.Parse throw), like Lua's %d.
            MatchCollection raw = AnySentinel.Matches(savedText);
            if (raw.Count == 0) { reason = Chunk.IsMatch(savedText) ? "no sentinel" : "no chunks"; return null; }
            foreach (Match any in raw)
                if (!Sentinel.IsMatch(any.Value)) { reason = "bad sentinel"; return null; }
            if (raw.Count > 1) { reason = "two sentinels"; return null; }
            Match s = Sentinel.Match(raw[0].Value);
            int revision = int.Parse(s.Groups[1].Value), count = int.Parse(s.Groups[2].Value);
            if (count == 0) { reason = "no chunks"; return null; }
            var parts = new Dictionary<int, string>();
            foreach (Match m in Chunk.Matches(savedText))
            {
                if (int.Parse(m.Groups[1].Value) != revision) { reason = "mixed revisions"; return null; }
                if (int.Parse(m.Groups[3].Value) != count) { reason = "count disagrees"; return null; }
                int part = int.Parse(m.Groups[2].Value);
                if (part < 1 || part > count) { reason = "part out of range"; return null; }
                parts[part] = m.Groups[4].Value;
            }
            if (parts.Count == 0) { reason = "no chunks"; return null; }
            var sb = new StringBuilder();
            for (int i = 1; i <= count; i++)
            {
                if (!parts.TryGetValue(i, out string? piece)) { reason = "missing part " + i; return null; }
                sb.Append(piece);
            }
            // The chunk regex takes any non-quote text, so the joined string is checked whole: \z, not $, so a trailing
            // newline can never reach Render's Lua string.
            if (sb.Length > MaxBase64Chars) { reason = "too much state: " + sb.Length; return null; }
            string b64 = sb.ToString();
            if (!Base64Shape.IsMatch(b64)) { reason = "bad base64"; return null; }
            return new Extracted { Revision = revision, Base64 = b64 };
        }

        public static string Render(int revision, string base64)
        {
            if (!Base64Shape.IsMatch(base64)) throw new ArgumentException("not base64");
            return "-- Generated by Crucible from this account's saved CrucibleCanvas.lua. Rewritten on every change. Do not edit.\n"
                + "CrucibleCanvasRecovery = { schema = 1, revision = " + revision + ", state = \"" + base64 + "\" }\n";
        }

        public static byte[] Bytes(string text) => NoBom.GetBytes(text);
    }
}
