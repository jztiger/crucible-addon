using System;
using System.Text;
using Xunit;

namespace Crucible.Tray.Tests
{
    /// <summary>The exact text the addon reads (spec §4.1): byte-exact, so the addon's own tests can use the same sample.</summary>
    public class TopologyFileTests
    {
        private static PlanResult Owner() => new PlanResult
        {
            Ok = true, Mode = "DUAL", Window = new Rect(-2560, 0, 5120, 1440),
            Mainhand = new Rect(2560, 0, 2560, 1440), Workspace = new Rect(0, 0, 2560, 1440),
            MainhandId = "MONITOR\\DELA0E3\\{4d36e96e}\\0001", WorkspaceId = "MONITOR\\LEN61F2\\{4d36e96e}\\0002",
        };

        [Fact]
        public void RendersTheSpecsText()
        {
            string text = TopologyFile.Render(Owner(), "0.100.0", new DateTime(2026, 10, 15, 23, 10, 0, DateTimeKind.Utc));
            Assert.Equal(
                "-- Generated by Crucible. Rewritten whenever the WoW window is spanned. Do not edit.\n" +
                "CrucibleCanvasTopology = {\n" +
                "  schema = 1,\n" +
                "  generatedAt = \"2026-10-15T23:10:00Z\",\n" +
                "  companionVersion = \"0.100.0\",\n" +
                "  mode = \"DUAL\",\n" +
                "  window = { width = 5120, height = 1440 },\n" +
                "  mainhand = { x = 2560, y = 0, width = 2560, height = 1440 },\n" +
                "  workspace = { x = 0, y = 0, width = 2560, height = 1440 },\n" +
                "  devices = { mainhand = \"MONITOR\\\\DELA0E3\\\\{4d36e96e}\\\\0001\", workspace = \"MONITOR\\\\LEN61F2\\\\{4d36e96e}\\\\0002\" },\n" +
                "}\n", text);
        }

        [Fact]
        public void EscapesQuotesAndBackslashesInDeviceIds_AndWritesNoBom()
        {
            PlanResult p = Owner(); p.MainhandId = "a\"b\\c";
            string text = TopologyFile.Render(p, "1.0.0", DateTime.UtcNow);
            Assert.Contains("mainhand = \"a\\\"b\\\\c\"", text);
            byte[] bytes = TopologyFile.Bytes(text);
            Assert.NotEqual(0xEF, bytes[0]);
            Assert.Equal(text, Encoding.UTF8.GetString(bytes));
        }

        [Fact]
        public void RefusesARefusedPlan()
        {
            Assert.Throws<InvalidOperationException>(() => TopologyFile.Render(new PlanResult { Ok = false, Reason = "x" }, "1.0.0", DateTime.UtcNow));
        }
    }
}
