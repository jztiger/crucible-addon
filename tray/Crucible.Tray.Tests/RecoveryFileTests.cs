using System;
using System.Linq;
using Xunit;

namespace Crucible.Tray.Tests
{
    /// <summary>The saved file is Lua, never parsed: the cc1 chunk strings are lifted by regex and refused whole on any doubt (spec §4.2).</summary>
    public class RecoveryFileTests
    {
        private static string Saved(params string[] chunks) =>
            "\nCrucibleCanvasDB = {\n[\"chunks\"] = {\n" + string.Join("", chunks.Select(c => "\"" + c + "\", -- [1]\n")) + "},\n}\n";
        private const string B = "eyJyZXZpc2lvbiI6MX0=";

        [Fact]
        public void LiftsTheChunksAndTheRevision()
        {
            Extracted? e = RecoveryFile.Extract(Saved("cc1:17:1/2:eyJy", "cc1:17:2/2:ZXZpc2lvbiI6MX0=", "cc1end:17:2"), out string reason);
            Assert.NotNull(e); Assert.Equal(17, e!.Revision); Assert.Equal(B, e.Base64);
        }

        [Theory]
        [InlineData("no sentinel", new[] { "cc1:1:1/1:QUJD" })]
        [InlineData("count disagrees", new[] { "cc1:1:1/2:QUJD", "cc1end:1:1" })]
        [InlineData("missing part", new[] { "cc1:1:2/2:QUJD", "cc1end:1:2" })]
        [InlineData("mixed revisions", new[] { "cc1:1:1/1:QUJD", "cc1end:2:1" })]
        [InlineData("two sentinels", new[] { "cc1:1:1/1:QUJD", "cc1end:1:1", "cc1end:1:1" })]
        [InlineData("bad sentinel", new[] { "cc1:1:1/1:QUJD", "cc1end:x:1" })]
        [InlineData("no chunks", new string[0])]
        [InlineData("bad base64", new[] { "cc1:1:1/1:QU*D", "cc1end:1:1" })]
        public void Refuses(string why, string[] chunks)
        {
            Assert.Null(RecoveryFile.Extract(Saved(chunks), out string reason));
            Assert.Contains(why, reason);
        }

        [Fact]
        public void ExactlyOneSentinel_TwoAreRefusedWhole_LikeTheAddon()
        {
            // Ruling R8/R8b (addon Task 3 review): the addon replaces its chunk list whole, so a file with two complete
            // sets, or a malformed sentinel, is refused - both readers must agree.
            Assert.Null(RecoveryFile.Extract(Saved("cc1:3:1/1:QUJD", "cc1end:3:1", "cc1:4:1/1:QUJE", "cc1end:4:1"), out string two));
            Assert.Contains("two sentinels", two);
            Assert.Null(RecoveryFile.Extract(Saved("cc1:1:1/1:QUJD", "cc1end:1:1", "cc1end:junk"), out string bad));
            Assert.Contains("bad sentinel", bad);
            Assert.Null(RecoveryFile.Extract(Saved("cc1:2:1/1:QUJD", "cc1:1:1/1:QUJE", "cc1end:2:1"), out string mixed));
            Assert.Contains("mixed revisions", mixed);
        }

        [Fact]
        public void RefusesWhatTheAddonRefuses_AndNeverThrows()
        {
            // Beyond the brief: the addon's State.fromChunks refuses a part outside 1..count and reads only ASCII digits (%d).
            Assert.Null(RecoveryFile.Extract(Saved("cc1:1:1/2:QUJD", "cc1:1:2/2:QUJD", "cc1:1:3/2:QUJD", "cc1end:1:2"), out string range));
            Assert.Contains("part out of range", range);
            Assert.Null(RecoveryFile.Extract(Saved("cc1:1:1/1:QUJD", "cc1end:1:0"), out string zero));
            Assert.Contains("no chunks", zero);
            Assert.Null(RecoveryFile.Extract(Saved("cc1:1:1/1:QUJD", "cc1end:\u0661:1"), out string arabic));
            Assert.Contains("bad sentinel", arabic);
            // A trailing newline is not base64: it must never reach a Lua string literal in Recovery.lua.
            Assert.Null(RecoveryFile.Extract(Saved("cc1:1:1/1:QUJD\n", "cc1end:1:1"), out string nl));
            Assert.Contains("bad base64", nl);
            Assert.Throws<ArgumentException>(() => RecoveryFile.Render(1, "QUJD\n"));
        }

        [Fact]
        public void RefusesNulBytesAndOversize()
        {
            Assert.Null(RecoveryFile.Extract("CrucibleCanvasDB = {\0}", out string r1)); Assert.Contains("nul", r1);
            string big = Saved("cc1:1:1/1:" + new string('A', RecoveryFile.MaxBase64Chars + 4), "cc1end:1:1");
            Assert.Null(RecoveryFile.Extract(big, out string r2)); Assert.Contains("too", r2);
        }

        [Fact]
        public void RendersTheSpecsText()
        {
            Assert.Equal(
                "-- Generated by Crucible from this account's saved CrucibleCanvas.lua. Rewritten on every change. Do not edit.\n" +
                "CrucibleCanvasRecovery = { schema = 1, revision = 17, state = \"" + B + "\" }\n",
                RecoveryFile.Render(17, B));
            Assert.Throws<ArgumentException>(() => RecoveryFile.Render(1, "not base64!"));
        }
    }
}
